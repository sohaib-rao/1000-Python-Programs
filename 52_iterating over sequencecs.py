# Print numbers from 1 to 5
for i in range(1, 6):
    print(i)

# Sum of first N numbers
total = 0
for i in range(1, 11):
    total += i
print(total)

# Print even numbers in a specific range
for i in range(2, 11, 2):
    print(i)

# Print odd numbers in a specific range
for i in range(1, 10, 2):
    print(i)

# Iterate through items in a list
fruits = ["apple", "banana", "mango"]
for fruit in fruits:
    print(fruit)

# Iterate through characters in a string
for char in "Python":
    print(char)