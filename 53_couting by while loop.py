# Count down from 5 to 1
count = 5
while count > 0:
    print(count)
    count -= 1

# Count up until a condition is met
count = 1
while count <= 5:
    print(count)
    count += 1

# Sum numbers until a threshold is reached
total = 0
num = 1
while total < 20:
    total += num
    num += 1
print(total)

# Factorial of a number using a while loop
n = 5
factorial = 1
while n > 0:
    factorial *= n
    n -= 1
print(factorial)