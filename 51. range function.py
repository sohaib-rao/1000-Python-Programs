# 1. Basic range (0 to 4)
for i in range(5):
    print(i)

# 2. Range with start and stop (2 to 5)
for i in range(2, 6):
    print(i)

# 3. Range with a step size (even numbers 0 to 8)
for i in range(0, 10, 2):
    print(i)

# 4. Counting backwards (5 down to 1)
for i in range(5, 0, -1):
    print(i)